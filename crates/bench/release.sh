#!/usr/bin/env bash
# Benchmarks a release and adds it to the history in docs/bench/history.
#
# Usage: crates/bench/release.sh [VERSION] [RXH-BENCH ARGS...]
#
# VERSION defaults to the workspace version. Run it on the release commit,
# on the same machine as the earlier releases. Writes:
#   <dir>/<VERSION>.json  raw results (`rxh-bench --json`)
#   <dir>/<VERSION>.md    machine, commit and the full report
#   <dir>/README.md       rxh across all releases, regressions marked
# Environment: HISTORY_DIR (default docs/bench/history), FORCE=1 to replace
# an existing VERSION.
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"
pkgid=$(cargo pkgid -p rxh-cli)
version=${1:-${pkgid##*@}}
shift || true
dir=${HISTORY_DIR:-docs/bench/history}

if [[ ! $version =~ ^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.]+)?$ ]]; then
    echo "not a version: $version" >&2
    exit 2
fi
if [[ -e $dir/$version.json && ${FORCE:-} != 1 ]]; then
    echo "$dir/$version.json exists, set FORCE=1 to replace it" >&2
    exit 2
fi
commit=$(git rev-parse --short HEAD)
if [[ $(git tag --points-at HEAD) != *"v$version"* ]]; then
    echo "warning: HEAD ($commit) is not tagged v$version" >&2
fi
if [[ -n $(git status --porcelain --untracked-files=no) ]]; then
    echo "warning: uncommitted changes, the numbers may not be those of $version" >&2
    commit="$commit (dirty)"
fi

cargo build --release -p rxh-cli -p rxh-bench
mkdir -p "$dir"
report=$(mktemp)
trap 'rm -f "$report"' EXIT

# rxh-bench exits with 1 when rxh fails a scenario: keep the results anyway,
# a failure belongs in the history too, and report it at the end.
status=0
./target/release/rxh-bench --docker --json "$dir/$version.json" "$@" >"$report" || status=$?
if [[ ! -s $dir/$version.json ]]; then
    echo "rxh-bench wrote no results" >&2
    exit 1
fi

cpu=$(lscpu 2>/dev/null | sed -n 's/^Model name: *//p' | head -n 1)
{
    echo "# rxh $version"
    echo
    echo "- Date: $(date -u +%Y-%m-%d)"
    echo "- Commit: $commit"
    echo "- CPU: ${cpu:-unknown} ($(nproc) threads)"
    echo "- System: $(uname -sr)"
    echo "- Docker: $(docker version --format '{{.Server.Version}}' 2>/dev/null || echo unknown)"
    echo "- Arguments: --docker $*"
    echo
    cat "$report"
} >"$dir/$version.md"

{
    echo "<!-- Generated by crates/bench/release.sh. Do not edit. -->"
    echo
    ./target/release/rxh-bench --history "$dir"
} >"$dir/README.md"

echo "wrote $dir/$version.json, $dir/$version.md and $dir/README.md" >&2
grep -A 1000 '^### Regressions' "$dir/README.md" >&2
exit "$status"
